// endings.js — the 8 endings, the branching logic, and epilogues that react to the player's choices.
//
//  Every ending needs at least 40 real minutes of play: the pyramid gate opens only at 14:00 world time
//  (6:00 + 8 world hours = 40 real minutes), and the time-out ending happens only after 2 hours.
//
//  timeout  ─┬─ shards < 4 ............................ 1 storm      (הסערה הנצחית)
//            └─ shards = 4 ............................ 2 unclaimed  (השחר שלא נתבע)
//  enter with < 4 shards (after 14:00) ................ 3 swallowed  (בלוע בחשכה)
//  claim  ──┬─ caravan rescued ........................ 4 sunking    (מלך השמש)
//           └─ caravan not rescued .................... 5 tyrant     (עריץ הדיונות)
//  seal   ──┬─ ≥ 8h left & caravan rescued ............ 6 oasis      (נווה המדבר נולד מחדש) – the true ending
//           ├─ ≥ 8h left & caravan not rescued ........ 7 silent     (השומר השקט)
//           └─ < 8h left .............................. 8 lastlight  (האור האחרון)

export const EARLY_HOURS = 8;

export const ENDINGS = [
  { id: 'storm', num: 1, title: 'הסערה הנצחית', tint: 0x8a5a2a },
  { id: 'unclaimed', num: 2, title: 'השחר שלא נתבע', tint: 0xffe0a0 },
  { id: 'swallowed', num: 3, title: 'בלוע בחשכה', tint: 0x400000 },
  { id: 'sunking', num: 4, title: 'מלך השמש', tint: 0xffa020 },
  { id: 'tyrant', num: 5, title: 'עריץ הדיונות', tint: 0xff1a10 },
  { id: 'oasis', num: 6, title: 'נווה המדבר נולד מחדש', tint: 0x7affc0, special: 'הסוף האמיתי' },
  { id: 'silent', num: 7, title: 'השומר השקט', tint: 0xffd36a },
  { id: 'lastlight', num: 8, title: 'האור האחרון', tint: 0xff7a30 },
];

export function determineEnding({ reason, shards, caravan, hoursLeft }) {
  const pick = (id) => ENDINGS.find((e) => e.id === id);
  if (reason === 'timeout') return pick(shards >= 4 ? 'unclaimed' : 'storm');
  if (reason === 'enter') return pick('swallowed');
  if (reason === 'claim') return pick(caravan ? 'sunking' : 'tyrant');
  if (reason === 'seal') {
    if (hoursLeft >= EARLY_HOURS) return pick(caravan ? 'oasis' : 'silent');
    return pick('lastlight');
  }
  return pick('storm');
}

